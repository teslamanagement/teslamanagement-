/**
 * Enhanced international search supporting full country name, partial names,
 * ISO country code (e.g. 'NG', 'US', 'GB'), and dialing code digits (e.g. '234', '+234', '1').
 */
export function searchCountries(query: string, countries: CountryData[] = WORLDWIDE_COUNTRIES): CountryData[] {
  const source = Array.isArray(countries) && countries.length > 0 ? countries : WORLDWIDE_COUNTRIES;
  const cleanQuery = (query || '').trim().toLowerCase();
  if (!cleanQuery) return source;

  const numericQuery = cleanQuery.replace(/^\+/, '');

  return source.filter(c => {
    if (!c) return false;
    const nameMatch = (c.name || '').toLowerCase().includes(cleanQuery);
    const isoMatch = (c.isoCode || '').toLowerCase() === cleanQuery || (c.isoCode || '').toLowerCase().startsWith(cleanQuery);
    const dialMatch = (c.dialCode || '').replace(/^\+/, '').includes(numericQuery) || (c.dialCode || '').includes(cleanQuery);
    return nameMatch || isoMatch || dialMatch;
  });
}

export function findCountryByIso(isoCode: string, countries: CountryData[] = WORLDWIDE_COUNTRIES): CountryData | undefined {
  const source = Array.isArray(countries) && countries.length > 0 ? countries : WORLDWIDE_COUNTRIES;
  if (!isoCode) return undefined;
  return source.find(c => c?.isoCode && c.isoCode.toUpperCase() === isoCode.toUpperCase());
}

export function findCountryByDialCode(dialCode: string, countries: CountryData[] = WORLDWIDE_COUNTRIES): CountryData | undefined {
  const source = Array.isArray(countries) && countries.length > 0 ? countries : WORLDWIDE_COUNTRIES;
  if (!dialCode) return undefined;
  const normalized = dialCode.startsWith('+') ? dialCode : `+${dialCode}`;
  return source.find(c => c?.dialCode === normalized);
}
